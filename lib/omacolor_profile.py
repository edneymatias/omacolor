"""EDID parsing and ICC (matrix/TRC) profile generation and validation. Stdlib only."""
import argparse
import glob
import json
import os
import re
import shutil
import struct
import subprocess
import sys

PRESETS_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "presets.json")
D50 = (0.9642, 1.0, 0.8249)
BRADFORD = ((0.8951, 0.2664, -0.1614), (-0.7502, 1.7135, 0.0367), (0.0389, -0.0685, 1.0296))


# ---------- EDID ----------

def parse_edid(data):
    if len(data) < 128 or data[:8] != bytes.fromhex("00ffffffffffff00"):
        raise ValueError("not an EDID base block")
    ident = (data[8] << 8) | data[9]
    make = "".join(chr(((ident >> shift) & 0x1F) + 64) for shift in (10, 5, 0))
    product = data[10] | (data[11] << 8)
    gamma = None if data[23] == 0xFF else (data[23] + 100) / 100.0
    low1, low2 = data[25], data[26]
    lows = [(low1 >> 6) & 3, (low1 >> 4) & 3, (low1 >> 2) & 3, low1 & 3,
            (low2 >> 6) & 3, (low2 >> 4) & 3, (low2 >> 2) & 3, low2 & 3]
    values = [((data[27 + i] << 2) | lows[i]) / 1024.0 for i in range(8)]
    rx, ry, gx, gy, bx, by, wx, wy = values
    if not any(values):
        raise ValueError("EDID has no chromaticities")
    if min(ry, gy, by, wy) <= 0:
        raise ValueError("EDID chromaticities are invalid (a y coordinate is zero)")
    area = abs(rx * (gy - by) + gx * (by - ry) + bx * (ry - gy)) / 2
    if area < 1e-4:
        raise ValueError("EDID primaries do not form a colour triangle")
    return {"make": make, "product": product,
            "primaries": {"r": [rx, ry], "g": [gx, gy], "b": [bx, by]},
            "white": [wx, wy], "gamma": gamma}


# ---------- ICC build ----------

def _s15(x):
    return struct.pack(">i", round(x * 65536))


def _xyz_tag(x, y, z):
    return b"XYZ \0\0\0\0" + _s15(x) + _s15(y) + _s15(z)


def _desc_tag(text):
    ascii_text = text.encode("ascii", "replace") + b"\0"
    return b"desc\0\0\0\0" + struct.pack(">I", len(ascii_text)) + ascii_text + b"\0" * (4 + 4 + 2 + 1 + 67)


def _text_tag(text):
    return b"text\0\0\0\0" + text.encode("ascii", "replace") + b"\0"


def _curve_tag(trc):
    if trc["type"] == "gamma":
        return b"curv\0\0\0\0" + struct.pack(">IH", 1, round(trc["value"] * 256)) + b"\0\0"
    points = 1024
    table = []
    for i in range(points):
        v = i / (points - 1)
        lin = v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
        table.append(round(lin * 65535))
    return b"curv\0\0\0\0" + struct.pack(">I", points) + struct.pack(">%dH" % points, *table)


def _xy_to_xyz(x, y):
    return [x / y, 1.0, (1 - x - y) / y]


def _mul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def _mv(m, v):
    return [sum(m[i][k] * v[k] for k in range(3)) for i in range(3)]


def _inv(m):
    (a, b, c), (d, e, f), (g, h, i) = m
    det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
    return [[(e * i - f * h) / det, (c * h - b * i) / det, (b * f - c * e) / det],
            [(f * g - d * i) / det, (a * i - c * g) / det, (c * d - a * f) / det],
            [(d * h - e * g) / det, (b * g - a * h) / det, (a * e - b * d) / det]]


def build_icc(primaries, white, trc, description):
    cols = [_xy_to_xyz(*primaries[k]) for k in ("r", "g", "b")]
    m = [[cols[j][i] for j in range(3)] for i in range(3)]
    white_xyz = _xy_to_xyz(*white)
    scale = _mv(_inv(m), white_xyz)
    m = [[m[i][j] * scale[j] for j in range(3)] for i in range(3)]
    src, dst = _mv(BRADFORD, white_xyz), _mv(BRADFORD, list(D50))
    diag = [[dst[i] / src[i] if i == j else 0.0 for j in range(3)] for i in range(3)]
    adapt = _mul(_inv([list(r) for r in BRADFORD]), _mul(diag, [list(r) for r in BRADFORD]))
    mp = _mul(adapt, m)
    curve = _curve_tag(trc)
    tags = {"desc": _desc_tag(description), "cprt": _text_tag("generated by omacolor"),
            "wtpt": _xyz_tag(*D50),
            "rXYZ": _xyz_tag(mp[0][0], mp[1][0], mp[2][0]),
            "gXYZ": _xyz_tag(mp[0][1], mp[1][1], mp[2][1]),
            "bXYZ": _xyz_tag(mp[0][2], mp[1][2], mp[2][2]),
            "rTRC": curve, "gTRC": curve, "bTRC": curve}
    table_end = 128 + 4 + 12 * len(tags)
    table, body, seen = b"", b"", {}
    for name, blob in tags.items():
        if blob not in seen:
            seen[blob] = table_end + len(body)
            body += blob + b"\0" * ((-len(blob)) % 4)
        table += name.encode() + struct.pack(">II", seen[blob], len(blob))
    size = table_end + len(body)
    header = struct.pack(">I4sI4s4s4s", size, b"", 0x02200000, b"mntr", b"RGB ", b"XYZ ")
    header += b"\0" * 12 + b"acsp" + b"\0" * 28 + _s15(D50[0]) + _s15(D50[1]) + _s15(D50[2])
    header = header.ljust(128, b"\0")
    return header + struct.pack(">I", len(tags)) + table + body


# ---------- validation ----------

def _header_problem(data):
    if len(data) < 128:
        return "file is shorter than an ICC header"
    if data[36:40] != b"acsp":
        return "not an ICC profile (missing 'acsp' signature)"
    if struct.unpack(">I", data[:4])[0] != len(data):
        return "ICC size field does not match the file size (truncated or corrupt)"
    if data[16:20] != b"RGB ":
        return "not an RGB profile"
    if data[12:16] != b"mntr":
        return "not a display (mntr) profile"
    return None


def check_icc(data):
    return _header_problem(data) is None


def validate_profile(path):
    try:
        with open(path, "rb") as handle:
            data = handle.read()
    except OSError as err:
        return {"ok": False, "reason": "cannot read file: %s" % err.strerror, "checked": "header"}
    problem = _header_problem(data)
    if problem:
        return {"ok": False, "reason": problem, "checked": "header"}
    if not shutil.which("transicc"):
        return {"ok": True, "reason": "", "checked": "header"}
    try:
        proc = subprocess.run(["transicc", "-i", path, "-o", path, "-t1"], input="0.5 0.5 0.5\n",
                              capture_output=True, text=True, timeout=5)
    except subprocess.TimeoutExpired:
        return {"ok": False, "reason": "lcms2 took too long to read the profile", "checked": "full"}
    if proc.returncode != 0:
        lines = [ln for ln in (proc.stdout + proc.stderr).splitlines() if "[transicc]" in ln]
        reason = lines[-1].replace("[transicc]:", "").strip() if lines else "lcms2 could not read the profile"
        return {"ok": False, "reason": reason, "checked": "full"}
    return {"ok": True, "reason": "", "checked": "full"}


# ---------- generation ----------

def _write_if_changed(path, data):
    """Writes atomically, and only when the content differs: Hyprland may be reading the file."""
    try:
        with open(path, "rb") as handle:
            if handle.read() == data:
                return False
    except OSError:
        pass
    tmp = path + ".tmp"
    with open(tmp, "wb") as handle:
        handle.write(data)
    os.replace(tmp, path)
    return True


def generate_presets(presets, outdir):
    os.makedirs(outdir, exist_ok=True)
    paths = []
    for entry in presets["presets"]:
        path = os.path.join(outdir, entry["id"] + ".icc")
        _write_if_changed(path, build_icc(entry["primaries"], presets["white"], entry["trc"], entry["id"]))
        paths.append(path)
    return paths


def generate_edid_profile(edid, out_path):
    info = parse_edid(edid)
    trc = {"type": "gamma", "value": info["gamma"] or 2.2}
    description = "EDID %s %04x" % (info["make"], info["product"])
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    _write_if_changed(out_path, build_icc(info["primaries"], info["white"], trc, description))
    return out_path


def list_user_profiles(directory):
    try:
        names = os.listdir(directory)
    except OSError:
        return []
    found = []
    for name in sorted(names, key=str.lower):
        path = os.path.join(directory, name)
        if name.lower().endswith(".icc") and os.path.isfile(path):
            found.append({"name": name, "path": path})
    return found


# ---------- CLI ----------

def _read_port_edid(port):
    if not re.fullmatch(r"[A-Za-z0-9._-]+", port):
        raise ValueError("invalid port name")
    for path in glob.glob("/sys/class/drm/card*-%s/edid" % port):
        with open(path, "rb") as handle:
            data = handle.read()
        if data:
            return data
    raise ValueError("no EDID for %s" % port)


def main(argv=None):
    parser = argparse.ArgumentParser(prog="omacolor-profile")
    sub = parser.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("presets")
    p.add_argument("--out", required=True)
    p = sub.add_parser("edid-info")
    p.add_argument("port")
    p = sub.add_parser("edid-profile")
    p.add_argument("port")
    p.add_argument("--out", required=True)
    p = sub.add_parser("check")
    p.add_argument("file")
    p = sub.add_parser("list-user")
    p.add_argument("dir")
    args = parser.parse_args(argv)
    try:
        if args.cmd == "presets":
            with open(PRESETS_PATH) as handle:
                for path in generate_presets(json.load(handle), args.out):
                    print(path)
        elif args.cmd == "edid-info":
            print(json.dumps(parse_edid(_read_port_edid(args.port))))
        elif args.cmd == "edid-profile":
            print(generate_edid_profile(_read_port_edid(args.port), args.out))
        elif args.cmd == "list-user":
            print(json.dumps(list_user_profiles(args.dir)))
        elif args.cmd == "check":
            result = validate_profile(args.file)
            print(json.dumps(result))
            return 0 if result["ok"] else 1
    except (ValueError, OSError) as err:
        print("omacolor-profile: %s" % err, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
